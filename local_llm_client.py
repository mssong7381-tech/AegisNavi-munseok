# -*- coding: utf-8 -*-
"""
local_llm_client.py
Local LLM Client for MaintQA Architecture:
Connects to local inference engines (Ollama on 127.0.0.1:11434 or llama-server on 127.0.0.1:50081)
Parameters enforced per architecture diagram:
- temperature: 0
- top_k: 1
- seed: 42
- slot 1 (sequential processing)
- thinking mode disabled / stripped
"""

import json
import re
import time
import urllib.request
import urllib.error

OLLAMA_URL = "http://127.0.0.1:11434"
LLAMA_SERVER_URL = "http://127.0.0.1:50081"
DEFAULT_MODEL = "qwen3:1.7b"

def clean_thinking_tags(text: str) -> str:
    """Strips <think>...</think> tags if generated by reasoning models."""
    cleaned = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL)
    cleaned = re.sub(r"^.*?assistant\s*", "", cleaned, flags=re.DOTALL | re.IGNORECASE)
    return cleaned.strip()

def call_local_llm(prompt: str, system_prompt: str = "", max_tokens: int = 600, timeout: int = 20) -> str:
    """
    Calls local LLM with architecture-compliant parameters:
    temperature=0, top_k=1, seed=42.
    Tries Ollama first, then llama-server.
    """
    # 1. Try Ollama Native / Chat API
    try:
        messages = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append({"role": "user", "content": prompt})

        payload = {
            "model": DEFAULT_MODEL,
            "messages": messages,
            "stream": False,
            "options": {
                "temperature": 0,
                "top_k": 1,
                "seed": 42,
                "num_predict": max_tokens
            }
        }
        req = urllib.request.Request(
            f"{OLLAMA_URL}/api/chat",
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=timeout) as res:
            res_data = json.loads(res.read().decode("utf-8"))
            content = res_data.get("message", {}).get("content", "")
            return clean_thinking_tags(content)
    except Exception as e_ollama:
        pass

    # 2. Try llama-server (127.0.0.1:50081)
    try:
        payload = {
            "prompt": f"System: {system_prompt}\nUser: {prompt}\nAssistant:",
            "temperature": 0,
            "top_k": 1,
            "seed": 42,
            "n_predict": max_tokens,
            "stop": ["User:", "\n\n\n"]
        }
        req = urllib.request.Request(
            f"{LLAMA_SERVER_URL}/completion",
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=timeout) as res:
            res_data = json.loads(res.read().decode("utf-8"))
            content = res_data.get("content", "")
            return clean_thinking_tags(content)
    except Exception as e_llama:
        pass

    return ""

def rewrite_followup_query(query: str, history: list) -> str:
    """
    Rewrites a short or demonstrative query using the last 3 conversation turns.
    According to diagram: '지시어가 있거나 8자 이하인 질문만 직전 3턴으로 재작성'
    """
    if not history:
        return query

    last_turns = history[-3:]
    context_str = ""
    for idx, turn in enumerate(last_turns, 1):
        q = turn.get("user", "")
        a = turn.get("assistant", "")
        context_str += f"대화{idx} - 사용자: {q} / 답변: {a[:100]}...\n"

    sys_prompt = (
        "당신은 선박 정비 질의응답 시스템의 후속 질문 해석기입니다. "
        "사용자의 질문에 지시어('그거', '그 작업', '이전 건')가 있거나 질문이 너무 짧으면, "
        "직전 3턴 대화 문맥을 파악하여 대상 선박과 대상 기기를 명시한 3인칭 완전한 질문 1문장으로 재작성하십시오. "
        "다른 설명 없이 오직 재작성된 질문 문장만 출력하십시오."
    )
    user_prompt = f"직전 대화 이력:\n{context_str}\n사용자 후속 질문: {query}\n재작성된 완전한 질문:"

    rewritten = call_local_llm(user_prompt, system_prompt=sys_prompt, max_tokens=100, timeout=10)
    if rewritten and len(rewritten) > 3 and not rewritten.startswith("{"):
        # Strip potential quotes
        rewritten = rewritten.strip('"\'')
        return rewritten

    # Deterministic rule-based fallback if LLM is unavailable
    # Extract vessel and equipment from the last turn
    last_turn_user = last_turns[-1].get("user", "")
    vessels = ["한바다호", "아라호", "백령호", "탐라호", "세종호", "장보고호"]
    vessel_found = next((v for v in vessels if v in last_turn_user), "선박")
    
    terms = ["주기관", "실린더", "과급기", "발전기", "청정기", "보일러", "조타기", "조수기", "유수분리기", "공기압축기", "냉동기", "평형수"]
    term_found = next((t for t in terms if t in last_turn_user), "해당 설비")

    if "비용" in query:
        return f"{vessel_found} {term_found} 관련 정비 비용은 얼마인가요?"
    elif "절차" in query or "방법" in query:
        return f"{vessel_found} {term_found} 작업 절차와 주의사항은?"
    elif "건수" in query or "몇 건" in query:
        return f"{vessel_found} {term_found} 관련 정비 건수는 몇 건인가요?"
    else:
        return f"{vessel_found} {term_found} {query}"

def translate_query_to_en(query: str, term_hints: list) -> str:
    """
    Translates Korean query into English for maintenance record search.
    According to diagram: '한국어 질문일 때만 영어로 번역 (대응표 표기를 힌트로 제공)'
    """
    hint_str = ", ".join([f"{h['ko']} -> {h['en']} ({h['abbr']})" for h in term_hints[:5]])
    sys_prompt = (
        "Translate the following Korean marine vessel maintenance query into a concise English search phrase. "
        "Use the provided technical terminology hints. Output ONLY the translated English search query."
    )
    user_prompt = f"Terminology Hints: {hint_str}\nKorean Query: {query}\nEnglish Search Query:"
    translated = call_local_llm(user_prompt, system_prompt=sys_prompt, max_tokens=60, timeout=10)
    if translated and len(translated) > 2:
        return translated.strip('"\'')
    
    # Deterministic fallback
    en_parts = []
    for h in term_hints:
        if h["ko"] in query:
            en_parts.append(h["en"])
    if "절차" in query or "방법" in query:
        en_parts.append("overhaul maintenance procedure")
    if "토크" in query:
        en_parts.append("torque specifications")
    if "압력" in query:
        en_parts.append("pressure test")
    return " ".join(en_parts) if en_parts else query

def translate_to_korean_dual(text: str) -> str:
    """
    Generates Korean dual-text translation for English responses.
    According to diagram: '한국어 병기 번역 (LLM) - 답 표시용·경로 뒤 1회 (병기를 켤 때만)'
    """
    sys_prompt = "선박 기관 정비 전문 번역사로서 아래의 정비 답변을 명확하고 격식 있는 한국어로 번역하십시오."
    user_prompt = f"번역할 본문:\n{text}\n한국어 번역문:"
    translated = call_local_llm(user_prompt, system_prompt=sys_prompt, max_tokens=500, timeout=12)
    return translated if translated else text

